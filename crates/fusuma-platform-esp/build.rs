//! Reads the board file named by `FUSUMA_BOARD` (a board under `boards/`, or a path to a `board.toml`), checks it,
//! turns on the drivers its controllers need (`fusuma_display`, `fusuma_touch` and `fusuma_backlight` cfgs) and
//! writes its numbers into `$OUT_DIR/board.rs`. A board with known controllers is therefore one file, no code.

use std::fmt::Write as _;
use std::path::PathBuf;
use std::{env, fs};

use fusuma_platform::board::{BoardFile, BoardShape, Wiring};

fn main() {
    let dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let boards = dir.join("boards");
    println!("cargo::rerun-if-env-changed=FUSUMA_BOARD");
    println!("cargo::rerun-if-env-changed=MCU");
    println!("cargo::rerun-if-changed=boards");
    for (key, values) in [
        ("fusuma_display", "\"co5300\", \"ek79007\", \"ssd1677\""),
        ("fusuma_touch", "\"ft3168\", \"gt911\""),
        ("fusuma_backlight", "\"ledc\""),
    ] {
        println!("cargo::rustc-check-cfg=cfg({key}, values({values}))");
    }

    let known = || {
        let mut names: Vec<String> = fs::read_dir(&boards)
            .map(|d| {
                d.filter_map(Result::ok)
                    .filter(|e| e.path().join("board.toml").exists())
                    .map(|e| e.file_name().to_string_lossy().into_owned())
                    .collect()
            })
            .unwrap_or_default();
        names.sort();
        names.join(", ")
    };
    let Ok(chosen) = env::var("FUSUMA_BOARD") else {
        fail(&format!(
            "set FUSUMA_BOARD to a board ({}) or a path to a board.toml; `nu scripts/showcase.nu` does",
            known()
        ));
    };
    let path = if chosen.ends_with(".toml") {
        PathBuf::from(&chosen)
    } else {
        boards.join(&chosen).join("board.toml")
    };
    println!("cargo::rerun-if-changed={}", path.display());
    let Ok(text) = fs::read_to_string(&path) else {
        fail(&format!(
            "no board '{chosen}' ({}); known: {}",
            path.display(),
            known()
        ));
    };
    let board =
        BoardFile::from_toml(&text, &path.display().to_string()).unwrap_or_else(|e| fail(&e.0));
    let Some(firmware) = &board.firmware else {
        fail(&format!(
            "{}: an ESP firmware needs a [firmware] table",
            path.display()
        ));
    };
    if let Ok(mcu) = env::var("MCU")
        && mcu != firmware.chip
    {
        fail(&format!(
            "{}: the board is an {}, but this build is for MCU={mcu}",
            path.display(),
            firmware.chip
        ));
    }
    let Some(display) = &board.display else {
        fail(&format!(
            "{}: an ESP firmware needs a [display]",
            path.display()
        ));
    };
    let Some(controller) = display.wiring.controller else {
        fail(&format!(
            "{}: display.controller is missing",
            path.display()
        ));
    };
    println!("cargo::rustc-cfg=fusuma_display=\"{}\"", controller.name);
    if let Some(t) = board.touch.as_ref().and_then(|t| t.wiring.controller) {
        println!("cargo::rustc-cfg=fusuma_touch=\"{}\"", t.name);
    }
    if let Some(b) = board.backlight.as_ref().and_then(|b| b.wiring.controller) {
        println!("cargo::rustc-cfg=fusuma_backlight=\"{}\"", b.name);
    }

    let mut out = String::new();
    let mut line = |s: String| {
        out.push_str(&s);
        out.push('\n');
    };
    line(format!(
        "// Generated by build.rs from {}. Do not edit.",
        path.display()
    ));
    line(format!(
        "/// The board's name.\npub(crate) const NAME: &str = {:?};",
        board.name
    ));
    line(format!(
        "/// One line about the board, for the log.\npub(crate) const ABOUT: &str = {:?};",
        board.about
    ));
    line(format!(
        "/// The chip, as `espflash` spells it.\npub(crate) const CHIP: &str = {:?};",
        firmware.chip
    ));
    line(format!(
        "/// Visible width in pixels.\npub(crate) const WIDTH: u32 = {};",
        display.width
    ));
    line(format!(
        "/// Visible height in pixels.\npub(crate) const HEIGHT: u32 = {};",
        display.height
    ));
    let shape = match display.shape {
        BoardShape::Rect => "fusuma::Shape::Rect".to_string(),
        BoardShape::Rounded(r) => format!("fusuma::Shape::Rounded({r})"),
        BoardShape::Circle => "fusuma::Shape::Circle".to_string(),
    };
    line(format!(
        "/// The screen's outline.\n#[allow(dead_code)]\npub(crate) const SHAPE: fusuma::Shape = {shape};"
    ));
    let mut screen = format!("fusuma::Screen::new({}, {}).with_shape(SHAPE)", display.width, display.height);
    if let Some(spec) = &board.screen {
        if spec.width_mm > 0 {
            screen += &format!(".with_size_mm({}, {})", spec.width_mm, spec.height_mm);
        }
        if let Some(form) = &spec.form {
            // The board file's names are checked on load, so each is a variant.
            let variant = format!("{}{}", form[..1].to_uppercase(), &form[1..]);
            screen += &format!(".with_form_factor(fusuma::FormFactor::{variant})");
        }
        let kind = if spec.reflective { "Reflective" } else { "Emissive" };
        screen += &format!(
            ".with_glass(fusuma::DisplayKind::{kind}, {}, {})",
            spec.depth_bits, spec.refresh_ms
        );
        let mut inputs = "fusuma::Inputs::NONE".to_string();
        for i in &spec.inputs {
            inputs += &format!(".with(fusuma::Inputs::{})", i.to_uppercase());
        }
        screen += &format!(".with_inputs({inputs})");
    }
    line(format!(
        "/// What the device is, from the board file's `[screen]`.\n#[allow(dead_code)]\npub(crate) const SCREEN: fusuma::Screen = {screen};"
    ));
    if controller.offset {
        line(format!(
            "/// Where the visible area starts in the panel's memory.\npub(crate) const OFFSET: [u16; 2] = {:?};",
            display.offset
        ));
    }
    line(format!(
        "/// Rectangles start and end on multiples of this.\n#[allow(dead_code)]\npub(crate) const GRID: u32 = {};",
        display.grid
    ));
    line(wiring("DISPLAY", &display.wiring));
    // Touch orientation is read whether or not there is a touch panel; the rest only for the parts there are.
    let touch = board.touch.as_ref();
    line(format!(
        "/// Flip the touch panel's x, y (after the swap).\npub(crate) const TOUCH_MIRROR: [bool; 2] = {:?};",
        touch.map_or([false, false], |t| t.mirror)
    ));
    line(format!(
        "/// Swap the touch panel's x and y.\npub(crate) const TOUCH_SWAP_XY: bool = {};",
        touch.is_some_and(|t| t.swap_xy)
    ));
    if let Some(t) = touch.filter(|t| t.wiring.controller.is_some()) {
        line(wiring("TOUCH", &t.wiring));
    }
    if let Some(b) = board.backlight.as_ref() {
        line(wiring("BACKLIGHT", &b.wiring));
        line(format!(
            "/// The backlight is on when its pin is low.\npub(crate) const BACKLIGHT_INVERT: bool = {};",
            b.invert
        ));
    }
    let (high, low) = board
        .power
        .as_ref()
        .map_or((vec![], vec![]), |p| (p.high.clone(), p.low.clone()));
    line(format!(
        "/// GPIOs driven high at boot, in order.\n#[allow(dead_code)]\npub(crate) const POWER_HIGH: &[i32] = &{:?};",
        high.iter().map(|&g| i32::from(g)).collect::<Vec<_>>()
    ));
    line(format!(
        "/// GPIOs driven low at boot, after the high ones.\n#[allow(dead_code)]\npub(crate) const POWER_LOW: &[i32] = &{:?};",
        low.iter().map(|&g| i32::from(g)).collect::<Vec<_>>()
    ));
    let (keys, active_low) = board
        .buttons
        .as_ref()
        .map_or((vec![], true), |b| {
            (b.keys.iter().map(|(n, g)| (n.clone(), i32::from(*g))).collect(), b.active_low)
        });
    line(format!(
        "/// The hardware keys: name and GPIO.\n#[allow(dead_code)]\npub(crate) const BUTTONS: &[(&str, i32)] = &{:?};",
        keys
    ));
    line(format!(
        "/// A pressed key pulls its pin low.\n#[allow(dead_code)]\npub(crate) const BUTTONS_ACTIVE_LOW: bool = {active_low};"
    ));
    let path = PathBuf::from(env::var("OUT_DIR").unwrap()).join("board.rs");
    fs::write(path, out).unwrap();
}

/// A part's pins and options as two constant tables.
fn wiring(part: &str, w: &Wiring) -> String {
    let mut s = String::new();
    let _ = write!(
        s,
        "/// The {part} pins from the board file: name and GPIOs.\npub(crate) const {part}_PINS: &[(&str, &[i32])] = &["
    );
    for (name, gpios) in &w.pins {
        let list: Vec<String> = gpios.iter().map(u8::to_string).collect();
        let _ = write!(s, "({name:?}, &[{}]), ", list.join(", "));
    }
    s.push_str("];");
    if !w.options.is_empty() {
        let _ = write!(
            s,
            "\n/// The {part} options from the board file, defaults filled in.\npub(crate) const {part}_OPTIONS: &[(&str, i64)] = &["
        );
        for (name, value) in &w.options {
            let _ = write!(s, "({name:?}, {value}), ");
        }
        s.push_str("];");
    }
    s
}

fn fail(msg: &str) -> ! {
    println!("cargo::error={msg}");
    std::process::exit(1)
}
