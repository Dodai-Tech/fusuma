//! With the `atlas` feature: writes `$OUT_DIR/atlas.rs`, a glyph atlas of the icons the app uses at each line height.
//! The icons are `fonts/toolkit.txt` (what the toolkit draws) and `[icons] used` in the file `FUSUMA_SETTINGS` names (the
//! app's `fusuma.toml`); the line heights are its `[fonts] sizes`, else 10, 15 and 20. Without the feature it does nothing.
#![expect(
    clippy::unwrap_used,
    clippy::panic,
    reason = "a build script: a broken font or setting must stop the build with the panic's message"
)]

#[cfg(feature = "atlas")]
fn main() {
    atlas::main();
}

#[cfg(not(feature = "atlas"))]
fn main() {}

#[cfg(feature = "atlas")]
mod atlas {
    use std::collections::BTreeMap;
    use std::fmt::Write as _;
    use std::path::PathBuf;
    use std::{env, fs};

    use ab_glyph::{Font, FontRef, ScaleFont, point};
    use serde::Deserialize;

    #[derive(Deserialize)]
    struct Settings {
        fonts: Option<Fonts>,
        icons: Option<Icons>,
    }

    #[derive(Deserialize)]
    struct Fonts {
        sizes: Option<Vec<u32>>,
    }

    #[derive(Deserialize)]
    struct Icons {
        used: Option<Vec<String>>,
    }

    pub fn main() {
        let dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
        let out = PathBuf::from(env::var("OUT_DIR").unwrap());
        println!("cargo::rerun-if-changed=build.rs");
        println!("cargo::rerun-if-changed=fonts");
        println!("cargo::rerun-if-changed=src/names.rs");
        println!("cargo::rerun-if-env-changed=FUSUMA_SETTINGS");
        let names: BTreeMap<String, char> =
            table(&fs::read_to_string(dir.join("src/names.rs")).unwrap());
        let mut used: Vec<String> = fs::read_to_string(dir.join("fonts/toolkit.txt"))
            .unwrap()
            .lines()
            .map(str::trim)
            .filter(|l| !l.is_empty() && !l.starts_with('#'))
            .map(str::to_string)
            .collect();
        let mut sizes = vec![10, 15, 20];
        if let Ok(path) = env::var("FUSUMA_SETTINGS") {
            println!("cargo::rerun-if-changed={path}");
            let text =
                fs::read_to_string(&path).unwrap_or_else(|e| panic!("FUSUMA_SETTINGS={path}: {e}"));
            let s: Settings = toml::from_str(&text).unwrap_or_else(|e| panic!("{path}: {e}"));
            used.extend(s.icons.and_then(|i| i.used).unwrap_or_default());
            if let Some(v) = s.fonts.and_then(|f| f.sizes) {
                sizes = v;
            }
        }
        assert!(!sizes.is_empty(), "[fonts] sizes is empty");
        sizes.sort_unstable();
        sizes.dedup();
        let mut cps: Vec<u32> = used
            .iter()
            .map(|n| {
                *names.get(n).unwrap_or_else(|| {
                    panic!("[icons] used: '{n}' is not a Lucide icon (see lucide.dev/icons)")
                }) as u32
            })
            .collect();
        cps.sort_unstable();
        cps.dedup();
        let data = fs::read(dir.join("fonts/lucide.ttf")).unwrap();
        let font = FontRef::try_from_slice(&data).unwrap();
        let mut src = String::from("// Generated by build.rs. Do not edit.\n\n");
        src.push_str("/// Icons have no kerning.\npub const KERN: Kerning = Kerning { upm: 1, pairs: &[] };\n");
        let mut consts = Vec::new();
        for &line in &sizes {
            assert!(
                (6..=96).contains(&line),
                "[fonts] sizes: {line} is not a line height of 6 to 96"
            );
            let name = format!("LUCIDE_{line}");
            one(&font, line, &cps, &name, &out, &mut src);
            consts.push(name);
        }
        let _ = writeln!(
            src,
            "/// Every atlas the build made, one a line height.\npub const ATLASES: &[Atlas] = &[{}];",
            consts.join(", ")
        );
        fs::write(out.join("atlas.rs"), src).unwrap();
    }

    /// The name and character of each icon in the generated `names.rs`, from its two tables.
    fn table(text: &str) -> BTreeMap<String, char> {
        let section = |start: &str| -> Vec<String> {
            let from = text
                .find(start)
                .unwrap_or_else(|| panic!("names.rs has no {start}"));
            let body = &text[from..];
            let body = &body[body.find("= [").unwrap() + 3..];
            // `cargo fmt` may put several on a line: split on the commas.
            body[..body.find("];").unwrap()]
                .split(',')
                .map(|l| l.trim().to_string())
                .filter(|l| !l.is_empty())
                .collect()
        };
        let names = section("static NAMES");
        let glyphs = section("static GLYPHS");
        assert_eq!(names.len(), glyphs.len());
        names
            .iter()
            .zip(&glyphs)
            .map(|(n, g)| {
                let hex = g.trim_start_matches("'\\u{").trim_end_matches("}'");
                (
                    n.trim_matches('"').to_string(),
                    char::from_u32(u32::from_str_radix(hex, 16).unwrap()).unwrap(),
                )
            })
            .collect()
    }

    /// One atlas: an icon fills a square as high as the line, standing on its bottom.
    fn one(
        font: &FontRef<'_>,
        line: u32,
        cps: &[u32],
        name: &str,
        out: &std::path::Path,
        src: &mut String,
    ) {
        let em = line as f32;
        // `PxScale` is the font's ascent-to-descent height in pixels, not the em: convert `em` pixels per em to it.
        let scale =
            ab_glyph::PxScale::from(em * font.height_unscaled() / font.units_per_em().unwrap());
        let scaled = font.as_scaled(scale);
        let mut glyphs = String::new();
        let mut coverage: Vec<u8> = Vec::new();
        for &cp in cps {
            let ch = char::from_u32(cp).unwrap();
            let id = font.glyph_id(ch);
            assert!(id.0 != 0, "U+{cp:04X} is not in the font");
            let advance = (scaled.h_advance(id) * 64.0).round().clamp(0.0, 65535.0) as u16;
            let glyph = id.with_scale_and_position(scale, point(0.0, em));
            let (left, top, w, h, at) = match font.outline_glyph(glyph) {
                Some(o) => {
                    let b = o.px_bounds();
                    let (w, h) = ((b.max.x - b.min.x) as u32, (b.max.y - b.min.y) as u32);
                    let stride = w.div_ceil(2) as usize;
                    let mut bits = vec![0u8; stride * h as usize];
                    o.draw(|x, y, c| {
                        let v = (c.clamp(0.0, 1.0) * 15.0).round() as u8;
                        let i = y as usize * stride + x as usize / 2;
                        bits[i] |= if x % 2 == 0 { v << 4 } else { v };
                    });
                    let at = coverage.len();
                    coverage.extend_from_slice(&bits);
                    (b.min.x as i32, b.min.y as i32, w, h, at)
                }
                None => (0, 0, 0, 0, coverage.len()),
            };
            assert!(
                w <= 255 && h <= 255 && (-128..=127).contains(&left) && (-128..=127).contains(&top)
            );
            let _ = write!(
                glyphs,
                "AtlasGlyph {{ ch: {cp}, advance: {advance}, left: {left}, top: {top}, width: {w}, height: {h}, at: {at} }}, "
            );
        }
        let bin = format!("{name}.bin");
        fs::write(out.join(&bin), &coverage).unwrap();
        let _ = writeln!(
            src,
            "/// Lucide with a line of {line} pixels.\npub const {name}: Atlas = Atlas {{ family: \"lucide\", bold: false, line: {line}, baseline: {line}, em64: {}, kern: &KERN, glyphs: &[{glyphs}], coverage: include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{bin}\")) }};",
            (em * 64.0).round() as u32
        );
    }
}
