//! With the `atlas` feature: rasterises every glyph of the enabled fonts that `COVERAGE` lists, at the line heights in
//! `FUSUMA_ATLAS_SIZES` (default "10,15,20"), to 4-bit coverage, and writes the tables into `$OUT_DIR/atlas.rs`
//! with the coverage in one `.bin` file per atlas. Metrics follow `fusuma-text`: a line of `n` pixels is a font of
//! `n * 100 / 121` pixels per em, and the baseline is the font's ascent below the top of the line.

#![cfg_attr(
    feature = "atlas",
    expect(
        clippy::unwrap_used,
        clippy::panic,
        reason = "a build script: a broken font or setting must stop the build with the panic's message"
    )
)]

fn main() {
    println!("cargo::rerun-if-changed=build.rs");
    #[cfg(feature = "atlas")]
    atlas::build();
}

#[cfg(feature = "atlas")]
mod atlas {
    use std::fmt::Write as _;
    use std::path::{Path, PathBuf};
    use std::{env, fs};

    use ab_glyph::{Font, FontRef, ScaleFont, point};

    /// The code points of `COVERAGE` in `src/lib.rs` (a test checks the two agree).
    const RANGES: [(u32, u32); 10] = [
        (0x20, 0x7E),
        (0xA0, 0x17F),
        (0x218, 0x21B),
        (0x2013, 0x2014),
        (0x2018, 0x201E),
        (0x2022, 0x2022),
        (0x2026, 0x2026),
        (0x20AC, 0x20AC),
        (0x2190, 0x2193),
        (0x2212, 0x2212),
    ];

    pub fn build() {
        println!("cargo::rerun-if-env-changed=FUSUMA_ATLAS_SIZES");
        let sizes: Vec<u32> = env::var("FUSUMA_ATLAS_SIZES")
            .unwrap_or_else(|_| "10,15,20".into())
            .split(',')
            .filter(|s| !s.trim().is_empty())
            .map(|s| {
                s.trim()
                    .parse()
                    .ok()
                    .filter(|n| (6..=96).contains(n))
                    .unwrap_or_else(|| {
                        panic!("FUSUMA_ATLAS_SIZES: '{s}' is not a line height of 6 to 96")
                    })
            })
            .collect();
        let feature = |f: &str| env::var(format!("CARGO_FEATURE_{f}")).is_ok();
        let faces = [
            ("INTER", "Sans", "Inter-Regular.ttf"),
            ("INTER_BOLD", "SansBold", "Inter-Bold.ttf"),
            ("JETBRAINS_MONO", "Mono", "JetBrainsMono-Regular.ttf"),
        ];
        let out = PathBuf::from(env::var("OUT_DIR").unwrap());
        let mut src = String::from("// Generated by build.rs. Do not edit.\n\n");
        let mut names = Vec::new();
        for (feat, face, file) in faces {
            if !feature(feat) {
                continue;
            }
            println!("cargo::rerun-if-changed=fonts/{file}");
            let data = fs::read(format!("fonts/{file}")).unwrap();
            let font = FontRef::try_from_slice(&data).unwrap();
            for &line in &sizes {
                let name = format!("{feat}_{line}");
                one(&font, face, line, &name, &out, &mut src);
                names.push(name);
            }
        }
        let _ = writeln!(
            src,
            "/// Every atlas the build made, smallest line first within each face."
        );
        let _ = writeln!(
            src,
            "pub const ATLASES: &[Atlas] = &[{}];",
            names.join(", ")
        );
        fs::write(out.join("atlas.rs"), src).unwrap();
    }

    fn one(font: &FontRef<'_>, face: &str, line: u32, name: &str, out: &Path, src: &mut String) {
        let em = line as f32 * 100.0 / 121.0;
        // `PxScale` is the font's ascent-to-descent height in pixels, not the em: convert `em` pixels per em to it.
        let scale =
            ab_glyph::PxScale::from(em * font.height_unscaled() / font.units_per_em().unwrap());
        let scaled = font.as_scaled(scale);
        let baseline = scaled.ascent();
        let mut glyphs = String::new();
        let mut coverage: Vec<u8> = Vec::new();
        for (lo, hi) in RANGES {
            for cp in lo..=hi {
                let Some(ch) = char::from_u32(cp) else {
                    continue;
                };
                let id = font.glyph_id(ch);
                if id.0 == 0 {
                    continue;
                }
                let advance = (scaled.h_advance(id) * 64.0).round().clamp(0.0, 65535.0) as u16;
                let glyph = id.with_scale_and_position(scale, point(0.0, baseline));
                let (left, top, w, h, at) = match font.outline_glyph(glyph) {
                    Some(o) => {
                        let b = o.px_bounds();
                        let (w, h) = ((b.max.x - b.min.x) as u32, (b.max.y - b.min.y) as u32);
                        let stride = w.div_ceil(2) as usize;
                        let mut bits = vec![0u8; stride * h as usize];
                        o.draw(|x, y, c| {
                            let v = (c.clamp(0.0, 1.0) * 15.0).round() as u8;
                            let i = y as usize * stride + x as usize / 2;
                            bits[i] |= if x % 2 == 0 { v << 4 } else { v };
                        });
                        let at = coverage.len();
                        coverage.extend_from_slice(&bits);
                        (b.min.x as i32, b.min.y as i32, w, h, at)
                    }
                    None => (0, 0, 0, 0, coverage.len()),
                };
                assert!(
                    w <= 255
                        && h <= 255
                        && (-128..=127).contains(&left)
                        && (-128..=127).contains(&top)
                );
                let _ = write!(
                    glyphs,
                    "AtlasGlyph {{ ch: {cp}, advance: {advance}, left: {left}, top: {top}, width: {w}, height: {h}, at: {at} }}, "
                );
            }
        }
        let bin = format!("{name}.bin");
        fs::write(out.join(&bin), &coverage).unwrap();
        let _ = writeln!(
            src,
            "/// {face} with a line of {line} pixels.\npub const {name}: Atlas = Atlas {{ font: AtlasFont::{face}, line: {line}, baseline: {}, glyphs: &[{glyphs}], coverage: include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{bin}\")) }};",
            baseline.round() as u32
        );
    }
}
