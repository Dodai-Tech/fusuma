//! Reads `fonts/catalog.toml` and writes `$OUT_DIR/fonts.rs`: the linked families (those whose cargo feature is on)
//! with their files and licences, every preset, the coverage and, with the `atlas` feature, a glyph atlas of each
//! linked face at each line height. The line heights are `[fonts] sizes` in the file `FUSUMA_SETTINGS` names (the
//! app's `fusuma.toml`), else the catalog's. Each file's own family name is checked against the catalog.
#![expect(
    clippy::unwrap_used,
    clippy::panic,
    reason = "a build script: a broken catalog, font or setting must stop the build with the panic's message"
)]

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

use serde::Deserialize;

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Catalog {
    defaults: Defaults,
    family: Vec<Family>,
    preset: Vec<Preset>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Defaults {
    coverage: String,
    sizes: Vec<u32>,
}

/// A family of the catalog. `url`, `bold_url`, `regular`, `bold` and `axes` say how `scripts/fonts.nu` fetches it;
/// the build only checks they are there.
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Family {
    id: String,
    name: String,
    role: String,
    about: String,
    url: String,
    bold_url: Option<String>,
    regular: Option<String>,
    bold: Option<String>,
    axes: Option<toml::Table>,
    /// An icon family: where its name table is, its licence, and the names cut out of it.
    codepoints_url: Option<String>,
    /// How the name table is written: `codepoints` (the default), `lucide` or `css`; only `scripts/fonts.nu` reads it.
    #[allow(dead_code)]
    codepoints_format: Option<String>,
    /// Tables dropped before cutting; only `scripts/fonts.nu` reads it.
    #[allow(dead_code)]
    drop_tables: Option<Vec<String>>,
    licence_url: Option<String>,
    icons: Option<Vec<String>>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Preset {
    id: String,
    about: String,
    sans: String,
    mono: String,
}

/// The `[fonts]` table of an app's settings file; only `sizes` matters here.
#[derive(Deserialize)]
struct Settings {
    fonts: Option<SettingsFonts>,
}

#[derive(Deserialize)]
struct SettingsFonts {
    sizes: Option<Vec<u32>>,
}

fn main() {
    let dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let fonts = dir.join("fonts");
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-changed=fonts");
    println!("cargo::rerun-if-env-changed=FUSUMA_SETTINGS");
    let catalog: Catalog = toml::from_str(&fs::read_to_string(fonts.join("catalog.toml")).unwrap())
        .unwrap_or_else(|e| panic!("fonts/catalog.toml: {e}"));
    let linked: Vec<&Family> = catalog
        .family
        .iter()
        .filter(|f| {
            assert!(!f.url.is_empty(), "fonts/catalog.toml: {} has no url", f.id);
            let _ = (&f.bold_url, &f.regular, &f.bold, &f.axes, &f.codepoints_url, &f.licence_url);
            assert_eq!(
                f.role == "icons",
                f.icons.is_some(),
                "fonts/catalog.toml: {}: `icons` is for an icon family, and an icon family needs it",
                f.id
            );
            env::var(format!(
                "CARGO_FEATURE_{}",
                f.id.to_uppercase().replace('-', "_")
            ))
            .is_ok()
        })
        .collect();

    let mut src =
        String::from("// Generated by build.rs from fonts/catalog.toml. Do not edit.\n\n");
    let _ = writeln!(
        src,
        "/// The characters every family is cut to, as Unicode ranges.\npub const COVERAGE: &str = {:?};",
        catalog.defaults.coverage
    );
    src.push_str("/// The families the enabled cargo features link, in catalog order.\npub const FAMILIES: &[Family] = &[\n");
    for f in &linked {
        let role = match f.role.as_str() {
            "sans" => "Sans",
            "mono" => "Mono",
            "icons" => "Icons",
            other => panic!(
                "fonts/catalog.toml: {}: role '{other}' is not sans, mono or icons",
                f.id
            ),
        };
        let icons = icon_table(&fonts.join(&f.id), f);
        let licence = ["LICENSE.txt", "OFL.txt"]
            .into_iter()
            .map(|n| fonts.join(&f.id).join(n))
            .find(|p| p.exists())
            .unwrap_or_else(|| panic!("fonts/{}: no LICENSE.txt or OFL.txt", f.id));
        let file = |weight: &str| {
            let path = fonts.join(&f.id).join(format!("{weight}.ttf"));
            let data = fs::read(&path).unwrap_or_else(|_| {
                panic!(
                    "{}: missing; run `nu scripts/fonts.nu fetch --family {}`",
                    path.display(),
                    f.id
                )
            });
            check_name(&data, &f.name, &path);
            format!(
                "FontFile {{ family: {:?}, bold: {}, data: include_bytes!({:?}) }}",
                f.name,
                weight == "bold",
                path.display().to_string()
            )
        };
        let bold = if role == "Sans" {
            format!("Some({})", file("bold"))
        } else {
            "None".into()
        };
        let _ = writeln!(
            src,
            "    Family {{ id: {:?}, name: {:?}, role: Role::{role}, about: {:?}, regular: {}, bold: {bold}, licence: include_str!({:?}), icons: &[{}] }},",
            f.id,
            f.name,
            f.about,
            file("regular"),
            licence.display().to_string(),
            icons
                .iter()
                .map(|(n, c)| format!("({n:?}, '\\u{{{c:x}}}')"))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }
    src.push_str("];\n\n/// Every preset of the catalog, linked or not; the first one whose families are linked is the default.\npub const PRESETS: &[Preset] = &[\n");
    for p in &catalog.preset {
        for (role, id) in [("sans", &p.sans), ("mono", &p.mono)] {
            let ok = catalog.family.iter().any(|f| &f.id == id && f.role == role);
            assert!(
                ok,
                "fonts/catalog.toml: preset {}: {role} '{id}' is no {role} family",
                p.id
            );
        }
        let _ = writeln!(
            src,
            "    Preset {{ id: {:?}, about: {:?}, sans: {:?}, mono: {:?} }},",
            p.id, p.about, p.sans, p.mono
        );
    }
    src.push_str(
        "];\n\n/// Every family id of the catalog, linked or not.\nconst CATALOG_IDS: &[&str] = &[",
    );
    for f in &catalog.family {
        let _ = write!(src, "{:?}, ", f.id);
    }
    src.push_str("];\n");
    let sizes = sizes(&catalog.defaults.sizes);
    let _ = writeln!(
        src,
        "\n/// The line heights glyph atlases are made at (with the `atlas` feature).\npub const ATLAS_SIZES: &[u16] = &{sizes:?};"
    );
    fs::write(out.join("fonts.rs"), &src).unwrap();

    #[cfg(feature = "atlas")]
    {
        let faces: Vec<atlas::Source> = linked
            .iter()
            .map(|f| atlas::Source {
                id: f.id.as_str(),
                sans: f.role == "sans",
                // Icons fill a square as high as the line; their codepoints are the coverage.
                // Sorted and without repeats: an atlas's glyphs are searched by character.
                ranges: (f.role == "icons").then(|| {
                    let mut cps: Vec<u32> = icon_table(&fonts.join(&f.id), f)
                        .iter()
                        .map(|(_, c)| *c)
                        .collect();
                    cps.sort_unstable();
                    cps.dedup();
                    cps.into_iter().map(|c| (c, c)).collect()
                }),
            })
            .collect();
        atlas::build(&faces, &fonts, &out, &sizes, &catalog.defaults.coverage);
    }
}

/// An icon family's names and characters from its `names.txt` (`name hex` a line), sorted by name, checked against
/// the catalog's list; empty for a text family.
fn icon_table(dir: &Path, f: &Family) -> Vec<(String, u32)> {
    let Some(want) = &f.icons else {
        return Vec::new();
    };
    let path = dir.join("names.txt");
    let text = fs::read_to_string(&path).unwrap_or_else(|_| {
        panic!(
            "{}: missing; run `nu scripts/fonts.nu fetch --family {}`",
            path.display(),
            f.id
        )
    });
    let mut table: Vec<(String, u32)> = text
        .lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| {
            let (name, hex) = l
                .split_once(' ')
                .unwrap_or_else(|| panic!("{}: '{l}'", path.display()));
            (
                name.to_string(),
                u32::from_str_radix(hex.trim(), 16).unwrap(),
            )
        })
        .collect();
    let mut got: Vec<&str> = table.iter().map(|(n, _)| n.as_str()).collect();
    // An entry is a name, or `logical=actual`: the table is by the name an app asks for.
    let mut asked: Vec<&str> = want
        .iter()
        .map(|e| e.split_once('=').map_or(e.as_str(), |(logical, _)| logical))
        .collect();
    got.sort_unstable();
    asked.sort_unstable();
    assert_eq!(
        got,
        asked,
        "{}: not the catalog's icons; fetch it again with --force",
        path.display()
    );
    table.sort();
    table
}

/// The line heights to make atlases at: the app's settings, else the catalog's.
fn sizes(defaults: &[u32]) -> Vec<u16> {
    let from_settings = env::var("FUSUMA_SETTINGS").ok().and_then(|path| {
        println!("cargo::rerun-if-changed={path}");
        let text =
            fs::read_to_string(&path).unwrap_or_else(|e| panic!("FUSUMA_SETTINGS={path}: {e}"));
        let s: Settings = toml::from_str(&text).unwrap_or_else(|e| panic!("{path}: {e}"));
        s.fonts.and_then(|f| f.sizes)
    });
    let sizes = from_settings.unwrap_or_else(|| defaults.to_vec());
    assert!(!sizes.is_empty(), "[fonts] sizes is empty");
    let mut out: Vec<u16> = sizes
        .iter()
        .map(|&n| {
            assert!(
                (6..=96).contains(&n),
                "[fonts] sizes: {n} is not a line height of 6 to 96"
            );
            n as u16
        })
        .collect();
    out.sort_unstable();
    out.dedup();
    out
}

/// Panics unless the font's own family name (name ID 16, else 1) is `want`: a layout asks for the family by name.
fn check_name(data: &[u8], want: &str, path: &Path) {
    let face =
        ttf_parser::Face::parse(data, 0).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let name = |id| {
        face.names()
            .into_iter()
            .find(|n| n.name_id == id && n.is_unicode())
            .and_then(|n| n.to_string())
    };
    let got = name(16).or_else(|| name(1)).unwrap_or_default();
    assert_eq!(
        got,
        want,
        "{}: the font calls itself '{got}', the catalog '{want}'",
        path.display()
    );
}

#[cfg(feature = "atlas")]
mod atlas {
    use std::fmt::Write as _;
    use std::fs;
    use std::path::Path;

    use ab_glyph::{Font, FontRef, ScaleFont, point};

    /// `coverage` ("U+0020-007E, U+00A0, ...") as code point ranges.
    fn ranges(coverage: &str) -> Vec<(u32, u32)> {
        coverage
            .split(',')
            .map(|part| {
                let part = part.trim().trim_start_matches("U+");
                let (lo, hi) = part.split_once('-').unwrap_or((part, part));
                let hex = |v: &str| u32::from_str_radix(v.trim_start_matches("U+"), 16).unwrap();
                (hex(lo), hex(hi))
            })
            .collect()
    }

    /// An atlas per face (a family's regular and, for a sans, bold) at each line height.
    /// A linked family to make atlases of.
    pub struct Source<'a> {
        pub id: &'a str,
        pub sans: bool,
        /// An icon family's codepoints; `None` for text, which gets the catalog's coverage.
        pub ranges: Option<Vec<(u32, u32)>>,
    }


    /// The kerning of a font among the printable ASCII characters, from its GPOS `kern` feature (what a shaper applies):
    /// `(units per em, pairs)`, each pair `(first << 16 | second, adjustment in font units)`, sorted, no zeros.
    fn kerning(data: &[u8]) -> (u16, Vec<(u32, i16)>) {
        use ttf_parser::gpos::{PairAdjustment, PositioningSubtable};
        let face = ttf_parser::Face::parse(data, 0).unwrap();
        let upm = face.units_per_em();
        let Some(gpos) = face.tables().gpos else {
            return (upm, Vec::new());
        };
        let kern = ttf_parser::Tag::from_bytes(b"kern");
        let mut lookups: Vec<u16> = Vec::new();
        for i in 0..gpos.features.len() {
            if let Some(f) = gpos.features.get(i)
                && f.tag == kern
            {
                lookups.extend(f.lookup_indices);
            }
        }
        lookups.sort_unstable();
        lookups.dedup();
        let chars: Vec<char> = (0x20u8..0x7f).map(char::from).collect();
        let mut pairs = Vec::new();
        for &a in &chars {
            for &b in &chars {
                let (Some(ga), Some(gb)) = (face.glyph_index(a), face.glyph_index(b)) else {
                    continue;
                };
                let mut total = 0i32;
                for &li in &lookups {
                    let Some(lookup) = gpos.lookups.get(li) else {
                        continue;
                    };
                    for st in lookup.subtables.into_iter::<PositioningSubtable>() {
                        let PositioningSubtable::Pair(p) = st else {
                            continue;
                        };
                        let hit = match p {
                            PairAdjustment::Format1 { coverage, sets } => coverage
                                .get(ga)
                                .and_then(|i| sets.get(i))
                                .and_then(|set| set.get(gb))
                                .map(|(v, _)| v.x_advance),
                            PairAdjustment::Format2 {
                                coverage,
                                classes,
                                matrix,
                            } => coverage.get(ga).and_then(|_| {
                                matrix
                                    .get((classes.0.get(ga), classes.1.get(gb)))
                                    .map(|(v, _)| v.x_advance)
                            }),
                        };
                        if let Some(v) = hit {
                            total += i32::from(v);
                            // The first subtable of a lookup that has the pair decides it.
                            break;
                        }
                    }
                }
                if total != 0 {
                    pairs.push(((a as u32) << 16 | b as u32, total.clamp(-32768, 32767) as i16));
                }
            }
        }
        pairs.sort_unstable();
        (upm, pairs)
    }

    pub fn build(families: &[Source<'_>], fonts: &Path, out: &Path, sizes: &[u16], coverage: &str) {
        let text_ranges = ranges(coverage);
        let mut src = String::from("// Generated by build.rs. Do not edit.\n\n");
        let mut names = Vec::new();
        for f in families {
            let (id, sans) = (f.id, f.sans);
            let ranges = f.ranges.as_ref().unwrap_or(&text_ranges);
            let weights: &[&str] = if sans {
                &["regular", "bold"]
            } else {
                &["regular"]
            };
            for &weight in weights {
                let data = fs::read(fonts.join(id).join(format!("{weight}.ttf"))).unwrap();
                let font = FontRef::try_from_slice(&data).unwrap();
                // How far below the baseline the family's icons reach, in font units (0 for a text family).
                let dip = if f.ranges.is_some() {
                    let face = ttf_parser::Face::parse(&data, 0).unwrap();
                    ranges
                        .iter()
                        .flat_map(|&(lo, hi)| lo..=hi)
                        .filter_map(char::from_u32)
                        .filter_map(|c| face.glyph_index(c))
                        .filter_map(|g| face.glyph_bounding_box(g))
                        .map(|b| -f32::from(b.y_min))
                        .fold(0.0f32, f32::max)
                } else {
                    0.0
                };
                let kern_name = format!(
                    "KERN_{}_{}",
                    id.to_uppercase().replace('-', "_"),
                    weight.to_uppercase()
                );
                let (upm, pairs) = if f.ranges.is_some() {
                    (1, Vec::new())
                } else {
                    kerning(&data)
                };
                let list: String = pairs
                    .iter()
                    .map(|(k, v)| format!("({k}, {v}), "))
                    .collect();
                let _ = writeln!(
                    src,
                    "/// The kerning of {id} {weight}: {} pairs.\npub const {kern_name}: Kerning = Kerning {{ upm: {upm}, pairs: &[{list}] }};",
                    pairs.len()
                );
                for &line in sizes {
                    let name = format!(
                        "{}_{}_{line}",
                        id.to_uppercase().replace('-', "_"),
                        weight.to_uppercase()
                    );
                    let atlas = Face {
                        family: id,
                        bold: weight == "bold",
                        icons: f.ranges.is_some(),
                        line: u32::from(line),
                        name: &name,
                    };
                    one(&font, &atlas, ranges, dip, &kern_name, out, &mut src);
                    names.push(name);
                }
            }
        }
        let _ = writeln!(src, "/// Every atlas the build made.");
        let _ = writeln!(
            src,
            "pub const ATLASES: &[Atlas] = &[{}];",
            names.join(", ")
        );
        fs::write(out.join("atlas.rs"), src).unwrap();
    }

    /// Which face at which line height, and the name of its constant.
    struct Face<'a> {
        family: &'a str,
        bold: bool,
        /// An icon font: the em is the line and the baseline its bottom, so an icon fills the line's square.
        icons: bool,
        line: u32,
        name: &'a str,
    }

    /// One face at one line height. Metrics follow `fusuma-text`: a line of `n` pixels is a font of `n * 100 / 121`
    /// pixels per em, and the baseline is the font's ascent below the top of the line.
    fn one(
        font: &FontRef<'_>,
        face: &Face<'_>,
        ranges: &[(u32, u32)],
        dip_units: f32,
        kern_name: &str,
        out: &Path,
        src: &mut String,
    ) {
        let (line, name) = (face.line, face.name);
        let em = if face.icons {
            line as f32
        } else {
            line as f32 * 100.0 / 121.0
        };
        // `PxScale` is the font's ascent-to-descent height in pixels, not the em: convert `em` pixels per em to it.
        let scale =
            ab_glyph::PxScale::from(em * font.height_unscaled() / font.units_per_em().unwrap());
        let scaled = font.as_scaled(scale);
        // An icon stands on the bottom of its line. One that dips below its font's baseline (Phosphor's do, by 3 % of the
        // em) would leave the square, so the whole family is lifted by the deepest dip and stays inside it.
        let dip = dip_units / f32::from(font.units_per_em().unwrap() as u16) * em;
        let baseline = if face.icons {
            em - dip
        } else {
            scaled.ascent()
        };
        let mut glyphs = String::new();
        let mut coverage: Vec<u8> = Vec::new();
        for &(lo, hi) in ranges {
            for cp in lo..=hi {
                let Some(ch) = char::from_u32(cp) else {
                    continue;
                };
                let id = font.glyph_id(ch);
                if id.0 == 0 {
                    continue;
                }
                let advance = (scaled.h_advance(id) * 64.0).round().clamp(0.0, 65535.0) as u16;
                let glyph = id.with_scale_and_position(scale, point(0.0, baseline));
                let (left, top, w, h, at) = match font.outline_glyph(glyph) {
                    Some(o) => {
                        let b = o.px_bounds();
                        let (w, h) = ((b.max.x - b.min.x) as u32, (b.max.y - b.min.y) as u32);
                        let stride = w.div_ceil(2) as usize;
                        let mut bits = vec![0u8; stride * h as usize];
                        o.draw(|x, y, c| {
                            let v = (c.clamp(0.0, 1.0) * 15.0).round() as u8;
                            let i = y as usize * stride + x as usize / 2;
                            bits[i] |= if x % 2 == 0 { v << 4 } else { v };
                        });
                        let at = coverage.len();
                        coverage.extend_from_slice(&bits);
                        (b.min.x as i32, b.min.y as i32, w, h, at)
                    }
                    None => (0, 0, 0, 0, coverage.len()),
                };
                assert!(
                    w <= 255
                        && h <= 255
                        && (-128..=127).contains(&left)
                        && (-128..=127).contains(&top)
                );
                let _ = write!(
                    glyphs,
                    "AtlasGlyph {{ ch: {cp}, advance: {advance}, left: {left}, top: {top}, width: {w}, height: {h}, at: {at} }}, "
                );
            }
        }
        let bin = format!("{name}.bin");
        fs::write(out.join(&bin), &coverage).unwrap();
        let _ = writeln!(
            src,
            "/// {}{} with a line of {line} pixels.\npub const {name}: Atlas = Atlas {{ family: {:?}, bold: {}, line: {line}, baseline: {}, em64: {}, kern: &{kern_name}, glyphs: &[{glyphs}], coverage: include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{bin}\")) }};",
            face.family,
            if face.bold { " bold" } else { "" },
            face.family,
            face.bold,
            // The line's bottom for an icon (the lift is in each glyph's `top`), the font's ascent for text.
            if face.icons {
                em.round()
            } else {
                baseline.round()
            } as u32,
            (em * 64.0).round() as u32
        );
    }
}
